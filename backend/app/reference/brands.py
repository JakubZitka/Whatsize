def build_brands() -> list[dict]:
    brands = []
    for row in _B:
        (brand_id, name, parent, country, segment, profile, run, women_sys, men_sys, website,
         cee, priority) = row
        ov = _OVERRIDES.get(brand_id, {})
        categories = list(PROFILES[profile]) + [c for c in ov.get("extra", [])
                                                 if c not in PROFILES[profile]]
        genders = {c[0] for c in categories}
        gender_focus = "U" if {"W", "M"} <= genders else ("W" if "W" in genders else "M")
        vanity = ov.get("vanity", (0.0, ""))
        brands.append({
            "brand_id": brand_id,
            "brand_name": name,
            "parent_group": parent,
            "country": country,
            "segment": segment,
            "gender_focus": gender_focus,
            "size_run": run,
            "women_size_system": women_sys,
            "men_size_system": men_sys,
            "tops_numeric": ov.get("tops_numeric", False),
            "shirt_system": ov.get("shirt_system", "NECK_CM"),
            "bra_system": ov.get("bra_system", "BRA_EU" if "W_BRA" in categories else ""),
            "bra_cups": ov.get("cups", ("A", "G")),
            "bra_bands": ov.get("bands", (60, 95)),
            "shoe_grid": ov.get("shoe_grid", "") if any(c.endswith("FOOTWEAR")
                                                        for c in categories) else "",
            "shoe_us_w_offset": ov.get("us_w_offset", 1.5),
            "shoe_us_uk_offset": ov.get("us_uk_offset", 1.0),
            "categories": categories,
            "fits": ov.get("fits", {}),
            "website": f"https://www.{website}" if website else "",
            "cee_presence": cee,
            "ingest_priority": priority,
            "vanity_offset_waist_cm": vanity[0],
            "vanity_offset_source": vanity[1],
            "publisher_guide_url": "",
        })
    # Footwear brands must label shoes in their own grid; fail loudly if not.
    for b in brands:
        if any(c.endswith("FOOTWEAR") for c in b["categories"]) and not b["shoe_grid"]:
            raise ValueError(f"{b['brand_id']}: footwear without a native grid")
    return brands
